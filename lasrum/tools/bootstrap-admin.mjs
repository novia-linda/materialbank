import fs from 'node:fs';
import readline from 'node:readline/promises';
import {Writable} from 'node:stream';
import {db,auth,putUserItems} from './admin.mjs';
const muted=new Writable({write(chunk,encoding,callback){callback();}});
const rl=readline.createInterface({input:process.stdin,output:muted,terminal:true});
process.stdout.write('E-postadressen för ditt Google-konto (visas inte): ');
const email=(await rl.question('')).trim().toLowerCase();rl.close();process.stdout.write('\n');
if(!email)throw Error('Ange e-postadressen som användes vid Google-inloggningen.');
const user=await auth.getUserByEmail(email);
if(user.email?.toLowerCase()!==email||!user.providerData.some(p=>p.providerId==='google.com'))throw Error('Kontot måste först ha loggat in i Läsrummet med Google.');
const access=db.doc('access/'+user.uid),previous=await access.get();
await access.set({...(previous.data()||{}),email:user.email,displayName:user.displayName||'Läsrummets administratör',status:'approved',role:'admin',approvedAt:new Date().toISOString()});
const data=JSON.parse(fs.readFileSync(new URL('../data/seed.json',import.meta.url),'utf8'));
const settings=db.doc('users/'+user.uid+'/settings/main');
if(!(await settings.get()).exists)await settings.set({version:1,theme:'dark',tags:['Till undervisningen','Prova själv','Läs igen'],sources:data.sources,categories:data.categories,seedIds:data.sources.map(s=>s.id)});
const feed=db.collection('users').doc(user.uid).collection('feed');
if((await feed.limit(1).get()).empty)await putUserItems(user.uid,data.items);
const {items,...meta}=data;
if(!(await db.doc('meta/seed').get()).exists)await db.doc('meta/seed').set(meta);
console.log('Administratören och Läsrummets startmaterial är klara. Logga ut och in igen i appen.');
